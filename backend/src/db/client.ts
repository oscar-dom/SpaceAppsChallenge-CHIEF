import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Database from 'better-sqlite3';
import { drizzle, type BetterSQLite3Database } from 'drizzle-orm/better-sqlite3';
import * as schema from './schema.js';

const here = path.dirname(fileURLToPath(import.meta.url));

/** Where the SQLite file lives. It is git-ignored; CHIEF_DB_PATH points to another file. */
export const DB_PATH = process.env.CHIEF_DB_PATH
  ? path.resolve(process.env.CHIEF_DB_PATH)
  : path.resolve(here, '..', '..', 'var', 'chief.db');

/** Folder with the SQL migrations generated by drizzle-kit. */
export const MIGRATIONS_DIR = path.resolve(here, '..', '..', 'drizzle');

export type Db = BetterSQLite3Database<typeof schema>;

export interface DatabaseHandle {
  db: Db;
  sqlite: Database.Database;
  close: () => void;
}

/**
 * Opens (and creates, if missing) the database with the mandatory PRAGMAs. Use ':memory:' in tests.
 * Only the backend writes to the database; always go through this function.
 */
export function createDatabase(file: string = DB_PATH): DatabaseHandle {
  if (file !== ':memory:') fs.mkdirSync(path.dirname(file), { recursive: true });
  const sqlite = new Database(file);
  sqlite.pragma('foreign_keys = ON');
  sqlite.pragma('busy_timeout = 5000');
  if (file !== ':memory:') sqlite.pragma('journal_mode = WAL');
  return { db: drizzle(sqlite, { schema }), sqlite, close: () => sqlite.close() };
}
